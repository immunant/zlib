fn scan_tree_state(
    bl_tree: &mut [crate::src::deflate::ct_data],
    tree: &mut [crate::src::deflate::ct_data],
    max_code: ::core::ffi::c_int,
) -> bool {
    let Ok(max_code) = usize::try_from(max_code) else {
        return false;
    };
    let Some(sentinel) = max_code.checked_add(1) else {
        return false;
    };
    if sentinel >= tree.len() || bl_tree.len() < crate::src::deflate::BL_CODES as usize {
        return false;
    }
    let mut n = 0usize;
    let mut prevlen: ::core::ffi::c_int = -1 as ::core::ffi::c_int;
    let mut curlen: ::core::ffi::c_int = 0;
    let mut nextlen = tree[0].dl.len as ::core::ffi::c_int;
    let mut count: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    let mut max_count: ::core::ffi::c_int = 7 as ::core::ffi::c_int;
    let mut min_count: ::core::ffi::c_int = 4 as ::core::ffi::c_int;
    if nextlen == 0 as ::core::ffi::c_int {
        max_count = 138 as ::core::ffi::c_int;
        min_count = 3 as ::core::ffi::c_int;
    }
    tree[sentinel].dl.len = 0xffff as ::core::ffi::c_int as crate::zutil_h::ush;
    while n <= max_code {
        curlen = nextlen;
        nextlen = tree[n + 1].dl.len as ::core::ffi::c_int;
        count += 1;
        if !(count < max_count && curlen == nextlen) {
            let Ok(code) = usize::try_from(curlen) else {
                return false;
            };
            if code >= bl_tree.len() {
                return false;
            }
            if count < min_count {
                bl_tree[code].fc.freq = (bl_tree[code].fc.freq as ::core::ffi::c_int
                    + count as crate::zutil_h::ush as ::core::ffi::c_int)
                    as crate::zutil_h::ush;
            } else if curlen != 0 as ::core::ffi::c_int {
                if curlen != prevlen {
                    bl_tree[code].fc.freq = bl_tree[code].fc.freq.wrapping_add(1);
                }
                bl_tree[REP_3_6 as usize].fc.freq =
                    bl_tree[REP_3_6 as usize].fc.freq.wrapping_add(1);
            } else if count <= 10 as ::core::ffi::c_int {
                bl_tree[REPZ_3_10 as usize].fc.freq =
                    bl_tree[REPZ_3_10 as usize].fc.freq.wrapping_add(1);
            } else {
                bl_tree[REPZ_11_138 as usize].fc.freq =
                    bl_tree[REPZ_11_138 as usize].fc.freq.wrapping_add(1);
            }
            count = 0 as ::core::ffi::c_int;
            prevlen = curlen;
            if nextlen == 0 as ::core::ffi::c_int {
                max_count = 138 as ::core::ffi::c_int;
                min_count = 3 as ::core::ffi::c_int;
            } else if curlen == nextlen {
                max_count = 6 as ::core::ffi::c_int;
                min_count = 3 as ::core::ffi::c_int;
            } else {
                max_count = 7 as ::core::ffi::c_int;
                min_count = 4 as ::core::ffi::c_int;
            }
        }
        n += 1;
    }
    true
}

fn send_tree_code_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
    bl_tree: &[crate::src::deflate::ct_data],
    code: ::core::ffi::c_int,
    extra: ::core::ffi::c_int,
    extra_len: ::core::ffi::c_int,
) -> bool {
    let Ok(code) = usize::try_from(code) else {
        return false;
    };
    let Some(node) = bl_tree.get(code) else {
        return false;
    };
    send_bits_state(
        pending_buf,
        pending,
        bi_buf,
        bi_valid,
        node.fc.code as ::core::ffi::c_int,
        node.dl.len as ::core::ffi::c_int,
    ) && send_bits_state(pending_buf, pending, bi_buf, bi_valid, extra, extra_len)
}

fn send_tree_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
    bl_tree: &[crate::src::deflate::ct_data],
    tree: &[crate::src::deflate::ct_data],
    max_code: ::core::ffi::c_int,
) -> bool {
    let Ok(max_code) = usize::try_from(max_code) else {
        return false;
    };
    let Some(sentinel) = max_code.checked_add(1) else {
        return false;
    };
    if sentinel >= tree.len() {
        return false;
    }

    let mut n = 0usize;
    let mut prevlen = -1;
    let mut nextlen = tree[0].dl.len as ::core::ffi::c_int;
    let mut count = 0;
    let mut max_count = if nextlen == 0 { 138 } else { 7 };
    let mut min_count = if nextlen == 0 { 3 } else { 4 };
    while n <= max_code {
        let curlen = nextlen;
        nextlen = tree[n + 1].dl.len as ::core::ffi::c_int;
        count += 1;
        if count >= max_count || curlen != nextlen {
            if count < min_count {
                while count != 0 {
                    if !send_tree_code_state(
                        pending_buf,
                        pending,
                        bi_buf,
                        bi_valid,
                        bl_tree,
                        curlen,
                        0,
                        0,
                    ) {
                        return false;
                    }
                    count -= 1;
                }
            } else if curlen != 0 {
                if curlen != prevlen {
                    if !send_tree_code_state(
                        pending_buf,
                        pending,
                        bi_buf,
                        bi_valid,
                        bl_tree,
                        curlen,
                        0,
                        0,
                    ) {
                        return false;
                    }
                    count -= 1;
                }
                if !send_tree_code_state(
                    pending_buf,
                    pending,
                    bi_buf,
                    bi_valid,
                    bl_tree,
                    REP_3_6,
                    count - 3,
                    2,
                ) {
                    return false;
                }
            } else if count <= 10 {
                if !send_tree_code_state(
                    pending_buf,
                    pending,
                    bi_buf,
                    bi_valid,
                    bl_tree,
                    REPZ_3_10,
                    count - 3,
                    3,
                ) {
                    return false;
                }
            } else if !send_tree_code_state(
                pending_buf,
                pending,
                bi_buf,
                bi_valid,
                bl_tree,
                REPZ_11_138,
                count - 11,
                7,
            ) {
                return false;
            }
            count = 0;
            prevlen = curlen;
            if nextlen == 0 {
                max_count = 138;
                min_count = 3;
            } else if curlen == nextlen {
                max_count = 6;
                min_count = 3;
            } else {
                max_count = 7;
                min_count = 4;
            }
        }
        n += 1;
    }
    true
}

fn finish_bl_tree_state(
    bl_tree: &[crate::src::deflate::ct_data],
    opt_len: &mut crate::zutil_h::ulg,
) -> Option<::core::ffi::c_int> {
    let mut max_blindex = crate::src::deflate::BL_CODES - 1 as ::core::ffi::c_int;
    while max_blindex >= 3 as ::core::ffi::c_int {
        let code = *bl_order.get(max_blindex as usize)? as usize;
        if bl_tree.get(code)?.dl.len != 0 as crate::zutil_h::ush {
            break;
        }
        max_blindex -= 1;
    }
    *opt_len = opt_len.wrapping_add(
        (3 as crate::zutil_h::ulg)
            .wrapping_mul(
                (max_blindex as crate::zutil_h::ulg).wrapping_add(1 as crate::zutil_h::ulg),
            )
            .wrapping_add(5 as crate::zutil_h::ulg)
            .wrapping_add(5 as crate::zutil_h::ulg)
            .wrapping_add(4 as crate::zutil_h::ulg),
    );
    Some(max_blindex)
}

fn build_bl_tree_state(s: &mut crate::src::deflate::deflate_state) -> Option<::core::ffi::c_int> {
    if !scan_tree_state(&mut s.bl_tree, &mut s.dyn_ltree, s.l_desc.max_code)
        || !scan_tree_state(&mut s.bl_tree, &mut s.dyn_dtree, s.d_desc.max_code)
    {
        return None;
    }
    let stat_desc = s.bl_desc.stat_desc?;
    let max_code = build_tree_state(
        &mut s.bl_tree,
        stat_desc,
        &mut s.heap,
        &mut s.heap_len,
        &mut s.heap_max,
        &mut s.depth,
        &mut s.bl_count,
        &mut s.opt_len,
        &mut s.static_len,
    )?;
    s.bl_desc.max_code = max_code;
    finish_bl_tree_state(&s.bl_tree, &mut s.opt_len)
}

fn send_all_trees_header_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
    bl_tree: &[crate::src::deflate::ct_data],
    lcodes: ::core::ffi::c_int,
    dcodes: ::core::ffi::c_int,
    blcodes: ::core::ffi::c_int,
) -> bool {
    if blcodes > crate::src::deflate::BL_CODES {
        return false;
    }
    if !send_bits_state(
        pending_buf,
        pending,
        bi_buf,
        bi_valid,
        lcodes.wrapping_sub(257),
        5,
    ) || !send_bits_state(
        pending_buf,
        pending,
        bi_buf,
        bi_valid,
        dcodes.wrapping_sub(1),
        5,
    ) || !send_bits_state(
        pending_buf,
        pending,
        bi_buf,
        bi_valid,
        blcodes.wrapping_sub(4),
        4,
    ) {
        return false;
    }
    let mut rank = 0;
    while rank < blcodes {
        let Some(&code) = bl_order.get(rank as usize) else {
            return false;
        };
        let Some(node) = bl_tree.get(code as usize) else {
            return false;
        };
        if !send_bits_state(
            pending_buf,
            pending,
            bi_buf,
            bi_valid,
            node.dl.len as ::core::ffi::c_int,
            3,
        ) {
            return false;
        }
        rank += 1;
    }
    true
}

