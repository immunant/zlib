fn detect_data_type(s: &crate::src::deflate::deflate_state) -> ::core::ffi::c_int {
    let mut block_mask: ::core::ffi::c_ulong = 0xf3ffc07f as ::core::ffi::c_ulong;
    let mut n: ::core::ffi::c_int = 0;
    n = 0 as ::core::ffi::c_int;
    while n <= 31 as ::core::ffi::c_int {
        if block_mask & 1 as ::core::ffi::c_ulong != 0
            && s.dyn_ltree[n as usize].freq as ::core::ffi::c_int != 0 as ::core::ffi::c_int
        {
            return crate::zlib_h::Z_BINARY;
        }
        n += 1;
        block_mask >>= 1 as ::core::ffi::c_int;
    }
    if s.dyn_ltree[9 as ::core::ffi::c_int as usize].freq as ::core::ffi::c_int
        != 0 as ::core::ffi::c_int
        || s.dyn_ltree[10 as ::core::ffi::c_int as usize].freq as ::core::ffi::c_int
            != 0 as ::core::ffi::c_int
        || s.dyn_ltree[13 as ::core::ffi::c_int as usize].freq as ::core::ffi::c_int
            != 0 as ::core::ffi::c_int
    {
        return crate::zlib_h::Z_TEXT;
    }
    n = 32 as ::core::ffi::c_int;
    while n < crate::src::deflate::LITERALS {
        if s.dyn_ltree[n as usize].freq as ::core::ffi::c_int != 0 as ::core::ffi::c_int {
            return crate::zlib_h::Z_TEXT;
        }
        n += 1;
    }
    return crate::zlib_h::Z_BINARY;
}

#[derive(Copy, Clone)]
enum FlushBlockChoice {
    Stored,
    Static,
    Dynamic,
}

fn tr_flush_block_decision(
    opt_len: crate::zutil_h::ulg,
    static_len: crate::zutil_h::ulg,
    stored_len: crate::zutil_h::ulg,
    strategy: ::core::ffi::c_int,
    level_positive: bool,
    buf_present: bool,
) -> FlushBlockChoice {
    let (mut opt_lenb, static_lenb) = if level_positive {
        let mut opt_lenb = opt_len
            .wrapping_add(3 as crate::zutil_h::ulg)
            .wrapping_add(7 as crate::zutil_h::ulg)
            >> 3 as ::core::ffi::c_int;
        let static_lenb = static_len
            .wrapping_add(3 as crate::zutil_h::ulg)
            .wrapping_add(7 as crate::zutil_h::ulg)
            >> 3 as ::core::ffi::c_int;
        if static_lenb <= opt_lenb || strategy == crate::zlib_h::Z_FIXED {
            opt_lenb = static_lenb;
        }
        (opt_lenb, static_lenb)
    } else {
        let static_lenb = stored_len.wrapping_add(5 as crate::zutil_h::ulg);
        (static_lenb, static_lenb)
    };
    if stored_len.wrapping_add(4 as crate::zutil_h::ulg) <= opt_lenb && buf_present {
        FlushBlockChoice::Stored
    } else if static_lenb == opt_lenb {
        FlushBlockChoice::Static
    } else {
        FlushBlockChoice::Dynamic
    }
}

#[export_name = "_tr_flush_block"]

pub unsafe extern "C" fn _tr_flush_block_ffi(
    mut s: *mut crate::src::deflate::deflate_state,
    mut buf: *mut crate::stdlib::charf,
    mut stored_len: crate::zutil_h::ulg,
    mut last: ::core::ffi::c_int,
) {
    let mut level_positive = false;
    let mut max_blindex: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    if {
        let state = &mut *s;
        if state.level > 0 as ::core::ffi::c_int {
            let strm = &mut *state.strm;
            if strm.data_type == crate::zlib_h::Z_UNKNOWN {
                strm.data_type = detect_data_type(state);
            }
            level_positive = true;
            true
        } else {
            false
        }
    } {
        let state = &mut *s;
        build_tree(state, TreeKind::Literal);
        build_tree(state, TreeKind::Distance);
        max_blindex = build_bl_tree(state);
    }
    let decision = if level_positive {
        let state = &*s;
        tr_flush_block_decision(
            state.opt_len,
            state.static_len,
            stored_len,
            state.strategy,
            true,
            !buf.is_null(),
        )
    } else {
        tr_flush_block_decision(
            0 as crate::zutil_h::ulg,
            0 as crate::zutil_h::ulg,
            stored_len,
            0 as ::core::ffi::c_int,
            false,
            !buf.is_null(),
        )
    };
    match decision {
        FlushBlockChoice::Stored => {
            _tr_stored_block_ffi(s, buf, stored_len, last);
        }
        FlushBlockChoice::Static => {
            {
                let state = &mut *s;
                let bits = send_bits_state(
                    state.bi_buf,
                    state.bi_valid,
                    ((1 as ::core::ffi::c_int) << 1 as ::core::ffi::c_int) + last,
                    3 as ::core::ffi::c_int,
                );
                let pending_buf = ::core::slice::from_raw_parts_mut(
                    state.pending_buf,
                    state.pending_buf_size as usize,
                );
                append_pending_bytes(pending_buf, &mut state.pending, &bits.bytes[..bits.len]);
                state.bi_buf = bits.bi_buf;
                state.bi_valid = bits.bi_valid;
            }
            compress_block(
                s,
                &raw const static_ltree as *const crate::src::deflate::ct_data,
                &raw const static_dtree as *const crate::src::deflate::ct_data,
            );
        }
        FlushBlockChoice::Dynamic => {
            {
                let state = &mut *s;
                let bits = send_bits_state(
                    state.bi_buf,
                    state.bi_valid,
                    ((2 as ::core::ffi::c_int) << 1 as ::core::ffi::c_int) + last,
                    3 as ::core::ffi::c_int,
                );
                let pending_buf = ::core::slice::from_raw_parts_mut(
                    state.pending_buf,
                    state.pending_buf_size as usize,
                );
                append_pending_bytes(pending_buf, &mut state.pending, &bits.bytes[..bits.len]);
                state.bi_buf = bits.bi_buf;
                state.bi_valid = bits.bi_valid;
            }
            {
                let state = &mut *s;
                let lcodes = state.l_desc.max_code + 1 as ::core::ffi::c_int;
                let dcodes = state.d_desc.max_code + 1 as ::core::ffi::c_int;
                let blcodes = max_blindex + 1 as ::core::ffi::c_int;
                let pending_buf = ::core::slice::from_raw_parts_mut(
                    state.pending_buf,
                    state.pending_buf_size as usize,
                );
                send_all_trees(state, pending_buf, lcodes, dcodes, blcodes);
            }
            compress_block(
                s,
                &raw mut (*s).dyn_ltree as *mut crate::src::deflate::ct_data_s
                    as *const crate::src::deflate::ct_data,
                &raw mut (*s).dyn_dtree as *mut crate::src::deflate::ct_data_s
                    as *const crate::src::deflate::ct_data,
            );
        }
    }
    init_block(&mut *s);
    if last != 0 {
        let state = &mut *s;
        let windup = bi_windup_state(state.bi_buf, state.bi_valid);
        let pending_buf =
            ::core::slice::from_raw_parts_mut(state.pending_buf, state.pending_buf_size as usize);
        append_pending_bytes(pending_buf, &mut state.pending, &windup.bytes[..windup.len]);
        state.bi_used = windup.bi_used;
        state.bi_buf = 0 as crate::zutil_h::ush;
        state.bi_valid = 0 as ::core::ffi::c_int;
    }
}
#[export_name = "_tr_tally"]

pub unsafe extern "C" fn _tr_tally_ffi(
    mut s: *mut crate::src::deflate::deflate_state,
    mut dist: ::core::ffi::c_uint,
    mut lc: ::core::ffi::c_uint,
) -> ::core::ffi::c_int {
    let state = &mut *s;
    let original_dist = dist;
    let sym_buf = ::core::slice::from_raw_parts_mut(state.sym_buf, state.sym_end as usize);
    append_sym_bytes(
        sym_buf,
        &mut state.sym_next,
        tr_tally_symbol_bytes(dist, lc),
    );
    if dist == 0 as ::core::ffi::c_uint {
        tr_tally_update_counts(
            &mut state.dyn_ltree,
            &mut state.dyn_dtree,
            &mut state.matches,
            dist,
            lc,
            0,
            0,
        );
    } else {
        let codes = tr_tally_match_codes(original_dist, lc);
        tr_tally_update_counts(
            &mut state.dyn_ltree,
            &mut state.dyn_dtree,
            &mut state.matches,
            original_dist,
            lc,
            codes.length_code,
            codes.dist_code,
        );
    }
    return (state.sym_next == state.sym_end) as ::core::ffi::c_int;
}
