unsafe extern "C" fn build_bl_tree(
    mut s: *mut crate::src::deflate::deflate_state,
) -> ::core::ffi::c_int {
    let mut max_blindex: ::core::ffi::c_int = 0;
    let state = &mut *s;
    let l_max_code = state.l_desc.max_code;
    scan_tree_lengths(&mut state.dyn_ltree, l_max_code, &mut state.bl_tree);
    let d_max_code = state.d_desc.max_code;
    scan_tree_lengths(&mut state.dyn_dtree, d_max_code, &mut state.bl_tree);
    build_tree(
        s,
        &raw mut (*s).bl_desc as *mut crate::src::deflate::tree_desc,
    );
    max_blindex = crate::src::deflate::BL_CODES - 1 as ::core::ffi::c_int;
    while max_blindex >= 3 as ::core::ffi::c_int {
        if (*s).bl_tree[bl_order[max_blindex as usize] as usize].dl as ::core::ffi::c_int
            != 0 as ::core::ffi::c_int
        {
            break;
        }
        max_blindex -= 1;
    }
    (*s).opt_len = (*s).opt_len.wrapping_add(
        (3 as crate::zutil_h::ulg)
            .wrapping_mul(
                (max_blindex as crate::zutil_h::ulg).wrapping_add(1 as crate::zutil_h::ulg),
            )
            .wrapping_add(5 as crate::zutil_h::ulg)
            .wrapping_add(5 as crate::zutil_h::ulg)
            .wrapping_add(4 as crate::zutil_h::ulg),
    );
    return max_blindex;
}

unsafe extern "C" fn send_all_trees(
    mut s: *mut crate::src::deflate::deflate_state,
    mut lcodes: ::core::ffi::c_int,
    mut dcodes: ::core::ffi::c_int,
    mut blcodes: ::core::ffi::c_int,
) {
    {
        let state = &mut *s;
        // The pending allocation is exactly `pending_buf_size` bytes.  All
        // bit fields below retain the original write order and use this one
        // bounded view for their occasional two-byte spill.
        let pending_buf =
            ::core::slice::from_raw_parts_mut(state.pending_buf, state.pending_buf_size as usize);
        send_bits(
            pending_buf,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            lcodes - 257 as ::core::ffi::c_int,
            5 as ::core::ffi::c_int,
        );
        send_bits(
            pending_buf,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            dcodes - 1 as ::core::ffi::c_int,
            5 as ::core::ffi::c_int,
        );
        send_bits(
            pending_buf,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            blcodes - 4 as ::core::ffi::c_int,
            4 as ::core::ffi::c_int,
        );
        let mut rank = 0 as ::core::ffi::c_int;
        while rank < blcodes {
            send_bits(
                pending_buf,
                &mut state.pending,
                &mut state.bi_buf,
                &mut state.bi_valid,
                state.bl_tree[bl_order[rank as usize] as usize].dl as ::core::ffi::c_int,
                3 as ::core::ffi::c_int,
            );
            rank += 1;
        }
    }
    send_tree(
        s,
        &raw mut (*s).dyn_ltree as *mut crate::src::deflate::ct_data_s
            as *mut crate::src::deflate::ct_data,
        lcodes - 1 as ::core::ffi::c_int,
    );
    send_tree(
        s,
        &raw mut (*s).dyn_dtree as *mut crate::src::deflate::ct_data_s
            as *mut crate::src::deflate::ct_data,
        dcodes - 1 as ::core::ffi::c_int,
    );
}
