fn bi_reverse(mut code: ::core::ffi::c_uint, mut len: ::core::ffi::c_int) -> ::core::ffi::c_uint {
    let mut res: ::core::ffi::c_uint = 0 as ::core::ffi::c_uint;
    loop {
        res |= code & 1 as ::core::ffi::c_uint;
        code >>= 1 as ::core::ffi::c_int;
        res <<= 1 as ::core::ffi::c_int;
        len -= 1;
        if len <= 0 as ::core::ffi::c_int {
            break;
        }
    }
    return res >> 1 as ::core::ffi::c_int;
}

fn append_pending(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bytes: &[crate::stdlib::Byte],
) -> bool {
    let Ok(start) = usize::try_from(*pending) else {
        return false;
    };
    let Some(end) = start.checked_add(bytes.len()) else {
        return false;
    };
    let Some(destination) = pending_buf.get_mut(start..end) else {
        return false;
    };
    destination.copy_from_slice(bytes);
    *pending = pending.wrapping_add(bytes.len() as crate::zutil_h::ulg);
    true
}

fn bi_flush_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
) {
    if *bi_valid == 16 as ::core::ffi::c_int {
        let bytes = [
            *bi_buf as crate::stdlib::Byte,
            (*bi_buf >> 8) as crate::stdlib::Byte,
        ];
        if append_pending(pending_buf, pending, &bytes) {
            *bi_buf = 0 as crate::zutil_h::ush;
            *bi_valid = 0 as ::core::ffi::c_int;
        }
    } else if *bi_valid >= 8 as ::core::ffi::c_int
        && append_pending(pending_buf, pending, &[*bi_buf as crate::stdlib::Byte])
    {
        *bi_buf = (*bi_buf >> 8) as crate::zutil_h::ush;
        *bi_valid -= 8 as ::core::ffi::c_int;
    }
}

fn bi_windup_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
    bi_used: &mut ::core::ffi::c_int,
) -> bool {
    let bytes = if *bi_valid > 8 as ::core::ffi::c_int {
        [
            *bi_buf as crate::stdlib::Byte,
            (*bi_buf >> 8) as crate::stdlib::Byte,
        ]
    } else if *bi_valid > 0 as ::core::ffi::c_int {
        [*bi_buf as crate::stdlib::Byte, 0]
    } else {
        [0, 0]
    };
    let count = if *bi_valid > 8 as ::core::ffi::c_int {
        2
    } else if *bi_valid > 0 as ::core::ffi::c_int {
        1
    } else {
        0
    };
    if count != 0 && !append_pending(pending_buf, pending, &bytes[..count]) {
        return false;
    }
    *bi_used =
        (*bi_valid - 1 as ::core::ffi::c_int & 7 as ::core::ffi::c_int) + 1 as ::core::ffi::c_int;
    *bi_buf = 0 as crate::zutil_h::ush;
    *bi_valid = 0 as ::core::ffi::c_int;
    true
}

fn send_bits_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
    value: ::core::ffi::c_int,
    len: ::core::ffi::c_int,
) -> bool {
    if !(0..=crate::src::deflate::Buf_size).contains(&len)
        || !(0..=crate::src::deflate::Buf_size).contains(bi_valid)
    {
        return false;
    }
    if *bi_valid > crate::src::deflate::Buf_size - len {
        let combined = *bi_buf as ::core::ffi::c_int
            | ((value as crate::zutil_h::ush as ::core::ffi::c_int) << *bi_valid);
        let bytes = [
            combined as crate::stdlib::Byte,
            (combined >> 8) as crate::stdlib::Byte,
        ];
        if !append_pending(pending_buf, pending, &bytes) {
            return false;
        }
        *bi_buf = (value as crate::zutil_h::ush as ::core::ffi::c_int
            >> (crate::src::deflate::Buf_size - *bi_valid))
            as crate::zutil_h::ush;
        *bi_valid += len - crate::src::deflate::Buf_size;
    } else {
        *bi_buf = (*bi_buf as ::core::ffi::c_int
            | ((value as crate::zutil_h::ush as ::core::ffi::c_int) << *bi_valid))
            as crate::zutil_h::ush;
        *bi_valid += len;
    }
    true
}

fn tr_stored_block_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
    bi_used: &mut ::core::ffi::c_int,
    stored: &[crate::stdlib::Byte],
    last: ::core::ffi::c_int,
) -> bool {
    if !send_bits_state(pending_buf, pending, bi_buf, bi_valid, last, 3) {
        return false;
    }
    if !bi_windup_state(pending_buf, pending, bi_buf, bi_valid, bi_used) {
        return false;
    }
    let stored_len = stored.len() as crate::zutil_h::ulg;
    let header = [
        stored_len as crate::zutil_h::ush as crate::stdlib::Byte,
        (stored_len as crate::zutil_h::ush >> 8) as crate::stdlib::Byte,
        (!stored_len as crate::zutil_h::ush) as crate::stdlib::Byte,
        (!stored_len as crate::zutil_h::ush >> 8) as crate::stdlib::Byte,
    ];
    append_pending(pending_buf, pending, &header) && append_pending(pending_buf, pending, stored)
}

fn tr_align_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
) {
    if !send_bits_state(pending_buf, pending, bi_buf, bi_valid, 2, 3) {
        return;
    }
    if send_bits_state(
        pending_buf,
        pending,
        bi_buf,
        bi_valid,
        static_ltree[256].fc.code as ::core::ffi::c_int,
        static_ltree[256].dl.len as ::core::ffi::c_int,
    ) {
        bi_flush_state(pending_buf, pending, bi_buf, bi_valid);
    }
}

unsafe extern "C" fn bi_flush(mut s: *mut crate::src::deflate::deflate_state) {
    if s.is_null() || (*s).pending_buf.is_null() {
        return;
    }
    let Ok(pending_len) = usize::try_from((*s).pending_buf_size) else {
        return;
    };
    let pending_buf = ::core::slice::from_raw_parts_mut((*s).pending_buf, pending_len);
    bi_flush_state(
        pending_buf,
        &mut (*s).pending,
        &mut (*s).bi_buf,
        &mut (*s).bi_valid,
    );
}

fn gen_next_codes(
    bl_count: &[crate::zutil_h::ush; crate::src::deflate::MAX_BITS as usize + 1],
) -> [crate::zutil_h::ush; crate::src::deflate::MAX_BITS as usize + 1] {
    let mut next_code: [crate::zutil_h::ush; 16] = [0; 16];
    let mut code: ::core::ffi::c_uint = 0 as ::core::ffi::c_uint;
    let mut bits = 1usize;
    while bits <= crate::src::deflate::MAX_BITS as usize {
        code =
            code.wrapping_add(bl_count[bits - 1] as ::core::ffi::c_uint) << 1 as ::core::ffi::c_int;
        next_code[bits] = code as crate::zutil_h::ush;
        bits += 1;
    }
    next_code
}

fn gen_codes_state(
    tree: &mut [crate::src::deflate::ct_data],
    max_code: ::core::ffi::c_int,
    bl_count: &[crate::zutil_h::ush; crate::src::deflate::MAX_BITS as usize + 1],
) -> bool {
    let Ok(max_code) = usize::try_from(max_code) else {
        return false;
    };
    if max_code >= tree.len() {
        return false;
    }
    let mut next_code = gen_next_codes(bl_count);
    for entry in &mut tree[..=max_code] {
        let len = entry.dl.len as usize;
        if len != 0 {
            let Some(code) = next_code.get_mut(len) else {
                return false;
            };
            entry.fc.code = bi_reverse(*code as ::core::ffi::c_uint, len as ::core::ffi::c_int)
                as crate::zutil_h::ush;
            *code = code.wrapping_add(1);
        }
    }
    true
}

unsafe extern "C" fn gen_codes(
    tree: *mut crate::src::deflate::ct_data,
    tree_len: usize,
    max_code: ::core::ffi::c_int,
    bl_count: *const crate::zutil_h::ushf,
) {
    if tree.is_null() || bl_count.is_null() {
        return;
    }
    let tree = ::core::slice::from_raw_parts_mut(tree, tree_len);
    let bl_count =
        &*(bl_count as *const [crate::zutil_h::ush; crate::src::deflate::MAX_BITS as usize + 1]);
    let _ = gen_codes_state(tree, max_code, bl_count);
}

