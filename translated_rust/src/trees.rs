fn bi_reverse(mut code: ::core::ffi::c_uint, mut len: ::core::ffi::c_int) -> ::core::ffi::c_uint {
    let mut res: ::core::ffi::c_uint = 0 as ::core::ffi::c_uint;
    loop {
        res |= code & 1 as ::core::ffi::c_uint;
        code >>= 1 as ::core::ffi::c_int;
        res <<= 1 as ::core::ffi::c_int;
        len -= 1;
        if len <= 0 as ::core::ffi::c_int {
            break;
        }
    }
    return res >> 1 as ::core::ffi::c_int;
}

/// Flush complete bytes from the bit buffer of an already-validated state.
///
/// `deflate_state` still carries raw owned allocations, so this helper stays
/// unsafe until the state owner is converted.  It does not, however, need to
/// recreate the exclusive state borrow from a raw pointer itself.
unsafe fn bi_flush(s: &mut crate::src::deflate::deflate_state) {
    if s.bi_valid == 16 as ::core::ffi::c_int {
        s.put_pending_byte(
            (s.bi_buf as ::core::ffi::c_int & 0xff as ::core::ffi::c_int) as crate::zutil_h::uch,
        );
        s.put_pending_byte(
            (s.bi_buf as ::core::ffi::c_int >> 8 as ::core::ffi::c_int) as crate::zutil_h::uch,
        );
        s.bi_buf = 0 as crate::zutil_h::ush;
        s.bi_valid = 0 as ::core::ffi::c_int;
    } else if s.bi_valid >= 8 as ::core::ffi::c_int {
        s.put_pending_byte(s.bi_buf as crate::stdlib::Byte);
        s.bi_buf = (s.bi_buf as ::core::ffi::c_int >> 8 as ::core::ffi::c_int) as crate::zutil_h::ush;
        s.bi_valid -= 8 as ::core::ffi::c_int;
    }
}

/// Finish the current bit buffer for an already-validated deflate state.
///
/// The state still owns raw allocations, so this remains an unsafe internal
/// operation.  Its caller, however, need not discard an existing exclusive
/// borrow merely to recreate it from a raw pointer.
unsafe fn bi_windup(s: &mut crate::src::deflate::deflate_state) {
    bi_windup_impl(s);
}

fn bi_windup_impl(s: &mut crate::src::deflate::deflate_state) {
    if s.bi_valid > 8 as ::core::ffi::c_int {
        s.put_pending_byte(
            (s.bi_buf as ::core::ffi::c_int & 0xff as ::core::ffi::c_int) as crate::zutil_h::uch,
        );
        s.put_pending_byte(
            (s.bi_buf as ::core::ffi::c_int >> 8 as ::core::ffi::c_int) as crate::zutil_h::uch,
        );
    } else if s.bi_valid > 0 as ::core::ffi::c_int {
        s.put_pending_byte(s.bi_buf as crate::stdlib::Byte);
    }
    s.bi_used =
        (s.bi_valid - 1 as ::core::ffi::c_int & 7 as ::core::ffi::c_int) + 1 as ::core::ffi::c_int;
    s.bi_buf = 0 as crate::zutil_h::ush;
    s.bi_valid = 0 as ::core::ffi::c_int;
}

fn gen_codes(
    tree: &mut [crate::src::deflate::ct_data],
    max_code: ::core::ffi::c_int,
    bl_count: &[crate::zutil_h::ush],
) {
    let mut next_code: [crate::zutil_h::ush; 16] = [0; 16];
    let mut code: ::core::ffi::c_uint = 0 as ::core::ffi::c_uint;
    let mut bits: ::core::ffi::c_int = 0;
    let mut n: ::core::ffi::c_int = 0;
    bits = 1 as ::core::ffi::c_int;
    while bits <= crate::src::deflate::MAX_BITS {
        code = code.wrapping_add(
            bl_count[(bits - 1 as ::core::ffi::c_int) as usize] as ::core::ffi::c_uint,
        ) << 1 as ::core::ffi::c_int;
        next_code[bits as usize] = code as crate::zutil_h::ush;
        bits += 1;
    }
    n = 0 as ::core::ffi::c_int;
    while n <= max_code {
        let len: ::core::ffi::c_int = tree[n as usize].len() as ::core::ffi::c_int;
        if len != 0 as ::core::ffi::c_int {
            let c2rust_fresh57 = next_code[len as usize];
            next_code[len as usize] = next_code[len as usize].wrapping_add(1);
            tree[n as usize].fc =
                bi_reverse(c2rust_fresh57 as ::core::ffi::c_uint, len) as crate::zutil_h::ush;
        }
        n += 1;
    }
}

