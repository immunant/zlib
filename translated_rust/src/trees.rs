fn compress_block_state(
    pending_buf: &mut [crate::stdlib::Byte],
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
    symbols: &[crate::zutil_h::uch],
    ltree: &[crate::src::deflate::ct_data],
    dtree: &[crate::src::deflate::ct_data],
) -> bool {
    let mut symbols = symbols.chunks_exact(3);
    if !symbols.remainder().is_empty() {
        return false;
    }
    for symbol in &mut symbols {
        let mut dist = (symbol[0] as ::core::ffi::c_uint)
            .wrapping_add((symbol[1] as ::core::ffi::c_uint) << 8);
        let mut lc = symbol[2] as ::core::ffi::c_int;
        if dist == 0 {
            if !send_tree_code_state(pending_buf, pending, bi_buf, bi_valid, ltree, lc, 0, 0) {
                return false;
            }
            continue;
        }

        let Some(&length_code) = crate::src::trees::_length_code.get(lc as usize) else {
            return false;
        };
        let code = length_code as usize;
        let Some(&extra) = extra_lbits.get(code) else {
            return false;
        };
        if !send_tree_code_state(
            pending_buf,
            pending,
            bi_buf,
            bi_valid,
            ltree,
            code as ::core::ffi::c_int + 257,
            0,
            0,
        ) {
            return false;
        }
        if extra != 0 {
            let Some(&base) = base_length.get(code) else {
                return false;
            };
            lc -= base;
            if !send_bits_state(pending_buf, pending, bi_buf, bi_valid, lc, extra) {
                return false;
            }
        }

        dist = dist.wrapping_sub(1);
        let dist_index = if dist < 256 {
            dist as usize
        } else {
            256usize.wrapping_add((dist >> 7) as usize)
        };
        let Some(&distance_code) = crate::src::trees::_dist_code.get(dist_index) else {
            return false;
        };
        let code = distance_code as usize;
        let Some(&extra) = extra_dbits.get(code) else {
            return false;
        };
        if !send_tree_code_state(
            pending_buf,
            pending,
            bi_buf,
            bi_valid,
            dtree,
            code as ::core::ffi::c_int,
            0,
            0,
        ) {
            return false;
        }
        if extra != 0 {
            let Some(&base) = base_dist.get(code) else {
                return false;
            };
            dist = dist.wrapping_sub(base as ::core::ffi::c_uint);
            if !send_bits_state(
                pending_buf,
                pending,
                bi_buf,
                bi_valid,
                dist as ::core::ffi::c_int,
                extra,
            ) {
                return false;
            }
        }
    }
    send_tree_code_state(
        pending_buf,
        pending,
        bi_buf,
        bi_valid,
        ltree,
        END_BLOCK,
        0,
        0,
    )
}

fn compress_block_from_state(
    pending_and_symbols: &mut [crate::stdlib::Byte],
    symbol_capacity: usize,
    symbol_len: usize,
    pending: &mut crate::zutil_h::ulg,
    bi_buf: &mut crate::zutil_h::ush,
    bi_valid: &mut ::core::ffi::c_int,
    ltree: &[crate::src::deflate::ct_data],
    dtree: &[crate::src::deflate::ct_data],
) -> bool {
    if symbol_capacity > pending_and_symbols.len()
        || symbol_len > pending_and_symbols.len() - symbol_capacity
    {
        return false;
    }
    let (pending_buf, symbol_storage) = pending_and_symbols.split_at_mut(symbol_capacity);
    compress_block_state(
        pending_buf,
        pending,
        bi_buf,
        bi_valid,
        &symbol_storage[..symbol_len],
        ltree,
        dtree,
    )
}

fn detect_data_type(tree: &[crate::src::deflate::ct_data]) -> ::core::ffi::c_int {
    let mut block_mask: ::core::ffi::c_ulong = 0xf3ffc07f as ::core::ffi::c_ulong;
    let mut n: ::core::ffi::c_int = 0;
    n = 0 as ::core::ffi::c_int;
    while n <= 31 as ::core::ffi::c_int {
        if block_mask & 1 as ::core::ffi::c_ulong != 0
            && tree[n as usize].fc.freq as ::core::ffi::c_int != 0 as ::core::ffi::c_int
        {
            return crate::zlib_h::Z_BINARY;
        }
        n += 1;
        block_mask >>= 1 as ::core::ffi::c_int;
    }
    if tree[9 as ::core::ffi::c_int as usize].fc.freq as ::core::ffi::c_int
        != 0 as ::core::ffi::c_int
        || tree[10 as ::core::ffi::c_int as usize].fc.freq as ::core::ffi::c_int
            != 0 as ::core::ffi::c_int
        || tree[13 as ::core::ffi::c_int as usize].fc.freq as ::core::ffi::c_int
            != 0 as ::core::ffi::c_int
    {
        return crate::zlib_h::Z_TEXT;
    }
    n = 32 as ::core::ffi::c_int;
    while n < crate::src::deflate::LITERALS {
        if tree[n as usize].fc.freq as ::core::ffi::c_int != 0 as ::core::ffi::c_int {
            return crate::zlib_h::Z_TEXT;
        }
        n += 1;
    }
    return crate::zlib_h::Z_BINARY;
}

fn tr_flush_block_state(
    state: &mut crate::src::deflate::deflate_state,
    data_type: &mut ::core::ffi::c_int,
    pending_and_symbols: &mut [crate::stdlib::Byte],
    stored: Option<&[crate::stdlib::Byte]>,
    stored_len: crate::zutil_h::ulg,
    last: ::core::ffi::c_int,
) -> bool {
    let Ok(symbol_capacity) = usize::try_from(state.lit_bufsize) else {
        return false;
    };
    let Ok(symbol_len) = usize::try_from(state.sym_next) else {
        return false;
    };
    let mut opt_lenb;
    let static_lenb;
    let mut max_blindex = 0;

    if state.level > 0 {
        if *data_type == crate::zlib_h::Z_UNKNOWN {
            *data_type = detect_data_type(&state.dyn_ltree);
        }
        if !build_l_tree_state(state) || !build_d_tree_state(state) {
            return false;
        }
        let Some(max_code) = build_bl_tree_state(state) else {
            return false;
        };
        max_blindex = max_code;
        opt_lenb = state.opt_len.wrapping_add(10) >> 3;
        static_lenb = state.static_len.wrapping_add(10) >> 3;
        if static_lenb <= opt_lenb || state.strategy == crate::zlib_h::Z_FIXED {
            opt_lenb = static_lenb;
        }
    } else {
        static_lenb = stored_len.wrapping_add(5);
        opt_lenb = static_lenb;
    }

    if stored_len.wrapping_add(4) <= opt_lenb {
        let Some(stored) = stored else {
            return false;
        };
        if !tr_stored_block_state(
            pending_and_symbols,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            &mut state.bi_used,
            stored,
            last,
        ) {
            return false;
        }
    } else if static_lenb == opt_lenb {
        if !send_bits_state(
            pending_and_symbols,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            2 + last,
            3,
        ) || !compress_block_from_state(
            pending_and_symbols,
            symbol_capacity,
            symbol_len,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            &static_ltree,
            &static_dtree,
        ) {
            return false;
        }
    } else {
        if !send_bits_state(
            pending_and_symbols,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            4 + last,
            3,
        ) || !send_all_trees_header_state(
            pending_and_symbols,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            &state.bl_tree,
            state.l_desc.max_code + 1,
            state.d_desc.max_code + 1,
            max_blindex + 1,
        ) || !send_tree_state(
            pending_and_symbols,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            &state.bl_tree,
            &state.dyn_ltree,
            state.l_desc.max_code,
        ) || !send_tree_state(
            pending_and_symbols,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            &state.bl_tree,
            &state.dyn_dtree,
            state.d_desc.max_code,
        ) || !compress_block_from_state(
            pending_and_symbols,
            symbol_capacity,
            symbol_len,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            &state.dyn_ltree,
            &state.dyn_dtree,
        ) {
            return false;
        }
    }
    reset_block(state);
    last == 0
        || bi_windup_state(
            pending_and_symbols,
            &mut state.pending,
            &mut state.bi_buf,
            &mut state.bi_valid,
            &mut state.bi_used,
        )
}

pub unsafe extern "C" fn _tr_flush_block(
    mut s: *mut crate::src::deflate::deflate_state,
    mut buf: *mut crate::stdlib::charf,
    mut stored_len: crate::zutil_h::ulg,
    mut last: ::core::ffi::c_int,
) {
    if s.is_null() {
        return;
    }
    let state = &mut *s;
    let Ok(pending_len) = usize::try_from(state.pending_buf_size) else {
        return;
    };
    let Ok(stored_len_usize) = usize::try_from(stored_len) else {
        return;
    };
    let strm = state.strm;
    if (pending_len != 0 && state.pending_buf.is_null()) || strm.is_null() {
        return;
    }
    let pending_and_symbols = if pending_len == 0 {
        &mut []
    } else {
        ::core::slice::from_raw_parts_mut(state.pending_buf, pending_len)
    };
    let stored = if buf.is_null() {
        None
    } else {
        Some(::core::slice::from_raw_parts(
            buf as *const crate::stdlib::Byte,
            stored_len_usize,
        ))
    };
    let _ = tr_flush_block_state(
        state,
        &mut (*strm).data_type,
        pending_and_symbols,
        stored,
        stored_len,
        last,
    );
}
#[export_name = "_tr_flush_block"]

pub unsafe extern "C" fn _tr_flush_block_ffi(
    mut s: *mut crate::src::deflate::deflate_state,
    mut buf: *mut crate::stdlib::charf,
    mut stored_len: crate::zutil_h::ulg,
    mut last: ::core::ffi::c_int,
) {
    _tr_flush_block(s, buf, stored_len, last)
}
pub fn _tr_tally(
    symbols: &mut [crate::zutil_h::uch],
    sym_next: &mut crate::stdlib::uInt,
    sym_end: crate::stdlib::uInt,
    matches: &mut crate::stdlib::uInt,
    dyn_ltree: &mut [crate::src::deflate::ct_data],
    dyn_dtree: &mut [crate::src::deflate::ct_data],
    mut dist: ::core::ffi::c_uint,
    lc: ::core::ffi::c_uint,
) -> ::core::ffi::c_int {
    let Ok(start) = usize::try_from(*sym_next) else {
        return 0;
    };
    let Some(end) = start.checked_add(3) else {
        return 0;
    };
    if end > symbols.len() || end > sym_end as usize {
        return 0;
    }
    let Some(symbol) = symbols.get_mut(start..end) else {
        return 0;
    };
    symbol[0] = dist as crate::zutil_h::uch;
    symbol[1] = (dist >> 8) as crate::zutil_h::uch;
    symbol[2] = lc as crate::zutil_h::uch;
    *sym_next = end as crate::stdlib::uInt;

    if dist == 0 {
        let Some(node) = dyn_ltree.get_mut(lc as usize) else {
            return 0;
        };
        node.fc.freq = node.fc.freq.wrapping_add(1);
    } else {
        *matches = matches.wrapping_add(1);
        dist = dist.wrapping_sub(1);
        let Some(&length_code) = crate::src::trees::_length_code.get(lc as usize) else {
            return 0;
        };
        let Some(node) = dyn_ltree.get_mut(length_code as usize + 257) else {
            return 0;
        };
        node.fc.freq = node.fc.freq.wrapping_add(1);

        let dist_index = if dist < 256 {
            dist as usize
        } else {
            256usize.wrapping_add((dist >> 7) as usize)
        };
        let Some(&distance_code) = crate::src::trees::_dist_code.get(dist_index) else {
            return 0;
        };
        let Some(node) = dyn_dtree.get_mut(distance_code as usize) else {
            return 0;
        };
        node.fc.freq = node.fc.freq.wrapping_add(1);
    }
    (*sym_next == sym_end) as ::core::ffi::c_int
}
#[export_name = "_tr_tally"]

pub unsafe extern "C" fn _tr_tally_ffi(
    mut s: *mut crate::src::deflate::deflate_state,
    mut dist: ::core::ffi::c_uint,
    mut lc: ::core::ffi::c_uint,
) -> ::core::ffi::c_int {
    if s.is_null() {
        return 0;
    }
    let state = &mut *s;
    let Ok(symbol_len) = usize::try_from(state.sym_end) else {
        return 0;
    };
    if symbol_len != 0 && state.sym_buf.is_null() {
        return 0;
    }
    let symbols = if symbol_len == 0 {
        &mut []
    } else {
        ::core::slice::from_raw_parts_mut(state.sym_buf, symbol_len)
    };
    _tr_tally(
        symbols,
        &mut state.sym_next,
        state.sym_end,
        &mut state.matches,
        &mut state.dyn_ltree,
        &mut state.dyn_dtree,
        dist,
        lc,
    )
}
